import { describe, expect, it } from 'vitest';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  ARMBIAN_BOARDS, armbianReleaseProblem, debugfsScript, defaultPartitionBytes, espFiles, espGrubCfg, ext4Superblock, GIB, GRUB_EFI,
  kernelArgs, linuxUserFrom, linuxUserProblem, localeFrom, parseReleaseFile, presetFile, rootfsEdits, rootfsGrubCfg, rootfsPartition,
  sortKernels, startupNsh, UPDATE_SCRIPT, type RootfsFacts,
} from '../src/woa/armbian';
import { buildGpt, SECTOR } from '../src/woa/gpt';

const UUID = '6f1d2c3b-4a59-4e7f-8d6c-5b4a39281706';
const OLD = '0bb4374f-5bdf-42c2-b951-03fc3cb84ca8';
const has = (cmd: string, args: string[]) => { const r = spawnSync(cmd, args); return r.status !== null && !r.error; };

const RELEASE = `# PLEASE DO NOT EDIT THIS FILE
BOARD=lckfb-taishanpi-3m
BOARD_NAME="Taishan Pi 3M"
ARCH=arm64
BOOT_SOC=rk3576
VERSION=26.11.0-trunk
`;

const facts = (over: Partial<RootfsFacts> = {}): RootfsFacts => ({
  uuid: OLD,
  fstab: { content: `UUID=${OLD} / ext4 defaults,errors=remount-ro 0 1\ntmpfs /tmp tmpfs defaults,nosuid 0 0\n`, mode: 0o644, uid: 0, gid: 0 },
  armbianEnv: { content: `verbosity=1\nrootdev=UUID=${OLD}\nrootfstype=ext4\n`, mode: 0o644, uid: 1001, gid: 1001 },
  kernels: ['7.3.4-edge-rockchip64'],
  dirs: ['/etc', '/etc/kernel', '/etc/kernel/postinst.d', '/etc/kernel/postrm.d', '/etc/initramfs', '/etc/initramfs/post-update.d', '/etc/systemd', '/etc/systemd/system',
    '/etc/systemd/system/multi-user.target.wants', '/usr', '/usr/sbin', '/usr/share', '/usr/share/alsa', '/usr/share/alsa/ucm2', '/usr/share/alsa/ucm2/conf.d',
    '/usr/share/alsa/ucm2/conf.d/simple-card', '/root', '/boot', '/var', '/var/lib', '/etc/default'],
  ...over,
});

const account = { user: 'woo', realName: 'Woo', password: `it's "quoted" $HOME \`x\` \\`, locale: 'zh_CN.UTF-8', timeZone: 'Asia/Shanghai' };

describe('Armbian image checks', () => {
  it('reads /etc/armbian-release and takes only an arm64 Armbian for the board', () => {
    const rel = parseReleaseFile(RELEASE);
    expect(rel.BOARD_NAME).toBe('Taishan Pi 3M');
    expect(armbianReleaseProblem(rel, 'tspi3m')).toBeNull();
    // The RK3566 TaishanPi is a different board.
    expect(armbianReleaseProblem({ ...rel, BOARD: 'lckfb-taishanpi' }, 'tspi3m')).toMatch(/lckfb-taishanpi"/);
    expect(armbianReleaseProblem({ ...rel, ARCH: 'armhf' }, 'tspi3m')).toMatch(/armhf/);
    expect(armbianReleaseProblem({ ...rel, BOARD: 'armsom-cm5-io', BOOT_SOC: 'rk3588' }, 'cm5io')).toMatch(/rk3588/);
    expect(armbianReleaseProblem({}, 'tspi3m')).toMatch(/not an Armbian image/);
    expect(armbianReleaseProblem(rel, 'rock4d')).toMatch(/not offered/);
  });

  it('finds the one root partition in a GPT or MBR image, and refuses others', () => {
    const disk = 12081152 + 34;
    const gpt = buildGpt({ diskSectors: disk, diskGuid: UUID, keep: null, parts: [
      { type: 'b921b045-1df0-41c3-af44-4c6f280d3fae', guid: OLD, firstLba: 32768, lastLba: 12081151, name: 'rootfs' },
    ] });
    expect(rootfsPartition(gpt.primary, disk * SECTOR)).toEqual({ offset: 32768 * SECTOR, bytes: 12048384 * SECTOR });
    expect(() => rootfsPartition(gpt.primary, 1 << 30)).toThrow(/shorter/);
    const two = buildGpt({ diskSectors: disk, diskGuid: UUID, keep: null, parts: [
      { type: 'c12a7328-f81f-11d2-ba4b-00a0c93ec93b', guid: OLD, firstLba: 2048, lastLba: 32767, name: 'efi' },
      { type: 'b921b045-1df0-41c3-af44-4c6f280d3fae', guid: UUID, firstLba: 32768, lastLba: 12081151, name: 'rootfs' },
    ] });
    expect(() => rootfsPartition(two.primary, disk * SECTOR)).toThrow(/2 partitions/);
    const mbr = new Uint8Array(34 * SECTOR);
    const dv = new DataView(mbr.buffer);
    mbr[446 + 4] = 0x83; dv.setUint32(446 + 8, 8192, true); dv.setUint32(446 + 12, 100000, true);
    mbr[510] = 0x55; mbr[511] = 0xaa;
    expect(rootfsPartition(mbr, 1e9)).toEqual({ offset: 8192 * SECTOR, bytes: 100000 * SECTOR });
    expect(() => rootfsPartition(new Uint8Array(34 * SECTOR), 1e9)).toThrow(/neither/);
  });

  it('reads the ext4 superblock', () => {
    const b = new Uint8Array(4096);
    const dv = new DataView(b.buffer, 1024);
    dv.setUint32(4, 1506048, true); dv.setUint32(24, 2, true); dv.setUint16(56, 0xef53, true); dv.setUint16(58, 1, true);
    b.set(Buffer.from(OLD.replace(/-/g, ''), 'hex'), 1024 + 104);
    b.set(new TextEncoder().encode('armbi_root'), 1024 + 120);
    expect(ext4Superblock(b)).toEqual({ uuid: OLD, bytes: 1506048 * 4096, label: 'armbi_root', clean: true });
    expect(() => ext4Superblock(new Uint8Array(4096))).toThrow(/ext4/);
  });

  it('sizes the partition from the root file system, rounded up to whole GiB', () => {
    expect(defaultPartitionBytes(12048384 * 512)).toBe(6 * GIB);
    expect(defaultPartitionBytes(6 * GIB)).toBe(6 * GIB);
  });

  it('orders kernels as sort -V -r does', () => {
    expect(sortKernels(['6.12.9-current', '7.3.4-edge-rockchip64', '7.3.10-edge-rockchip64', '7.3.4-edge-rockchip64'])).toEqual(['7.3.10-edge-rockchip64', '7.3.4-edge-rockchip64', '6.12.9-current']);
  });
});

describe('Armbian boot configuration', () => {
  const boot = { boardId: 'tspi3m' as const, uuid: UUID, defaultOs: 'armbian' as const, timeout: 5, appVersion: 't' };

  it('boots by file system UUID with the firmware devicetree, and masks the screen service on the TaishanPi 3M', () => {
    const cfg = espGrubCfg(boot);
    expect(cfg).toContain(`set armbian_uuid=${UUID}`);
    expect(cfg).toContain('search --no-floppy --fs-uuid --set=root $armbian_uuid');
    expect(cfg).toContain('configfile /boot/grub/armbian-uefi.cfg');
    expect(cfg).toContain('linux /vmlinuz root=UUID=$armbian_uuid rootwait rw console=ttyS0,1500000 console=tty1 loglevel=4 systemd.mask=lckfb-tspi-3m-screen.service');
    expect(cfg).toContain('chainloader ($esp)/EFI/Microsoft/Boot/bootmgfw.efi');
    expect(cfg).not.toMatch(/devicetree|fdt/);
    expect(cfg).toMatch(/set default=0/);
    expect(espGrubCfg({ ...boot, defaultOs: 'windows' })).toMatch(/set default=windows/);
    expect(kernelArgs('cm5io')).not.toContain('systemd.mask');
    expect(() => espGrubCfg({ ...boot, uuid: 'x' })).toThrow();
  });

  it('adds the boot option from the UEFI Shell once, first or last in the boot order', () => {
    const nsh = startupNsh('armbian');
    expect(nsh).toContain('bcfg boot add 0 %a:\\EFI\\armbian\\grubaa64.efi "Armbian"');
    expect(nsh).toContain('mv %a:\\startup.nsh %a:\\EFI\\armbian\\startup.nsh.done');
    expect(nsh.split('\r\n').length).toBeGreaterThan(10);
    expect(startupNsh('windows')).toContain('bcfg boot add 99 ');
  });

  it('ships the GRUB binary it was built with, and the files for the EFI partition', () => {
    const efi = new Uint8Array(readFileSync(join(__dirname, '..', 'resources', 'armbian', GRUB_EFI.file)));
    expect(efi.length).toBe(GRUB_EFI.size);
    expect(createHash('sha256').update(efi).digest('hex')).toBe(GRUB_EFI.sha256);
    // Its embedded config is the one in resources/armbian (memdisk is uncompressed).
    expect(Buffer.from(efi).includes(Buffer.from('configfile "${cmdpath}/grub.cfg"'))).toBe(true);
    const files = espFiles(efi, boot);
    expect(files.map((f) => f.path)).toEqual(['armbian-esp/EFI/armbian/grubaa64.efi', 'armbian-esp/EFI/armbian/grub.cfg', 'armbian-esp/startup.nsh']);
    expect(() => espFiles(efi.subarray(1), boot)).toThrow();
  });

  it.skipIf(!has('sh', ['-c', 'true']) || spawnSync('sort', ['-V'], { input: '' }).status !== 0)('writes the same menu from the shell hook as the imager does', () => {
    const root = mkdtempSync(join(tmpdir(), 'armbian-hook-'));
    try {
      mkdirSync(join(root, 'boot'));
      mkdirSync(join(root, 'etc', 'default'), { recursive: true });
      for (const v of ['7.3.4-edge-rockchip64', '7.3.10-edge-rockchip64', '6.12.9-current']) writeFileSync(join(root, 'boot', `vmlinuz-${v}`), 'k');
      writeFileSync(join(root, 'boot', 'vmlinuz-7.3.4-edge-rockchip64.bak'), 'x');
      const ops = rootfsEdits({ ...boot, defaultOs: 'windows', facts: facts({ kernels: ['7.3.4-edge-rockchip64', '7.3.10-edge-rockchip64', '6.12.9-current', '7.3.4-edge-rockchip64.bak'] }), account: null, sshKey: '' });
      const defaults = ops.find((x) => x.op === 'write' && x.path === '/etc/default/armbian-uefi')!;
      writeFileSync(join(root, 'etc', 'default', 'armbian-uefi'), (defaults as { content: string }).content);
      writeFileSync(join(root, 'update.sh'), UPDATE_SCRIPT);
      const r = spawnSync('sh', [join(root, 'update.sh')], { env: { ...process.env, ARMBIAN_UEFI_ROOT: root, ARMBIAN_UEFI_UUID: UUID }, encoding: 'utf8' });
      expect(r.stderr).toBe('');
      expect(r.status).toBe(0);
      const fromShell = readFileSync(join(root, 'boot', 'grub', 'armbian-uefi.cfg'), 'utf8');
      const fromImager = (ops.find((x) => x.op === 'write' && x.path === '/boot/grub/armbian-uefi.cfg') as { content: string }).content;
      expect(fromShell).toBe(fromImager);
      expect(fromShell.indexOf('7.3.10')).toBeLessThan(fromShell.indexOf('Linux 7.3.4-edge'));
      expect(fromShell).toContain('set default=windows');
      expect(fromShell).toContain(`linux /boot/vmlinuz-7.3.10-edge-rockchip64 root=UUID=${UUID} rootwait rw console=ttyS0,1500000`);
      // A kernel upgrade: the old version goes, a new one comes; the hook is run again.
      rmSync(join(root, 'boot', 'vmlinuz-7.3.4-edge-rockchip64'));
      writeFileSync(join(root, 'boot', 'vmlinuz-7.4.1-edge-rockchip64'), 'k');
      expect(spawnSync('sh', [join(root, 'update.sh')], { env: { ...process.env, ARMBIAN_UEFI_ROOT: root, ARMBIAN_UEFI_UUID: UUID } }).status).toBe(0);
      const after = readFileSync(join(root, 'boot', 'grub', 'armbian-uefi.cfg'), 'utf8');
      expect(after).toBe(rootfsGrubCfg({ uuid: UUID, cmdline: kernelArgs('tspi3m'), defaultOs: 'windows', timeout: 5, kernels: ['7.4.1-edge-rockchip64', '7.3.10-edge-rockchip64', '6.12.9-current', '7.3.4-edge-rockchip64.bak'] }));
      expect(after.indexOf('7.4.1')).toBeLessThan(after.indexOf('7.3.10'));
      expect(after).not.toContain("Linux 7.3.4-edge-rockchip64'");
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});

describe('Armbian first-start presets', () => {
  it('makes a Linux user name from the Windows one', () => {
    expect(linuxUserFrom('Woo')).toBe('woo');
    expect(linuxUserFrom('Ga Hing')).toBe('gahing');
    expect(linuxUserFrom('9lives')).toBe('u9lives');
    expect(linuxUserProblem('woo')).toBeNull();
    expect(linuxUserProblem('Woo')).toBe('armbian.user.bad');
    expect(linuxUserProblem('root')).toBe('armbian.user.reserved');
    expect(localeFrom('zh-CN')).toBe('zh_CN.UTF-8');
    expect(localeFrom('en')).toBe('en_US.UTF-8');
    expect(localeFrom('')).toBe('en_US.UTF-8');
  });

  it.skipIf(!has('bash', ['-c', 'true']))('writes a preset file bash reads back exactly, whatever the password holds', () => {
    const text = presetFile(account);
    const dir = mkdtempSync(join(tmpdir(), 'preset-'));
    try {
      writeFileSync(join(dir, 'p'), text);
      expect(spawnSync('bash', ['-n', join(dir, 'p')]).status).toBe(0);
      const r = spawnSync('bash', ['-c', `. "$1"; printf '%s\\n' "$PRESET_ROOT_PASSWORD" "$PRESET_USER_NAME" "$PRESET_USER_PASSWORD" "$PRESET_LOCALE" "$PRESET_TIMEZONE" "$SET_LANG_BASED_ON_LOCATION" "$PRESET_NET_CHANGE_DEFAULTS" "$PRESET_DEFAULT_REALNAME" "$PRESET_USER_SHELL"`, 'x', join(dir, 'p')], { encoding: 'utf8' });
      expect(r.stdout.split('\n').slice(0, 9)).toEqual([account.password, 'woo', account.password, 'zh_CN.UTF-8', 'Asia/Shanghai', 'n', '0', 'Woo', 'bash']);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
    expect(() => presetFile({ ...account, password: 'a\nb' })).toThrow();
    expect(() => presetFile({ ...account, user: 'Woo' })).toThrow();
  });
});

describe('the changes to the root file system', () => {
  const boot = { boardId: 'tspi3m' as const, uuid: UUID, defaultOs: 'armbian' as const, timeout: 5 };

  it('moves fstab and armbianEnv.txt to the new UUID, and puts the board fixes in', () => {
    const ops = rootfsEdits({ ...boot, facts: facts(), account, sshKey: 'ssh-ed25519 AAAAC3Nza key@pc' });
    const w = (p: string) => ops.find((x) => x.path === p) as Extract<typeof ops[number], { op: 'write' }>;
    expect(w('/etc/fstab').content).toBe(`UUID=${UUID} / ext4 defaults,errors=remount-ro 0 1\ntmpfs /tmp tmpfs defaults,nosuid 0 0\n`);
    expect(w('/boot/armbianEnv.txt').content).toContain(`rootdev=UUID=${UUID}`);
    expect(w('/boot/armbianEnv.txt')).toMatchObject({ uid: 1001, gid: 1001, mode: 0o644 });
    expect(ops).toContainEqual({ op: 'symlink', path: '/etc/systemd/system/lckfb-tspi-3m-screen.service', target: '/dev/null' });
    expect(w('/usr/share/alsa/ucm2/conf.d/simple-card/LCKFB-TaishanPi3M-0.conf').content).toBe(ARMBIAN_BOARDS.tspi3m!.files[0].content);
    expect(w('/usr/share/alsa/ucm2/conf.d/simple-card/LCKFB-TaishanPi3M-0.conf').content).toContain('Needle "rockchipes8388"');
    expect(w('/usr/share/alsa/ucm2/conf.d/simple-card/LCKFB-TaishanPi3M-0.conf').content).toContain('"${CardId}"');
    // Native DSI is the default: GNOME maps the touch screen itself, so no calibration rule.
    expect(ops.some((x) => /udev|LIBINPUT|monitors\.xml/.test(x.path + ('content' in x ? x.content : '')))).toBe(false);
    expect(w('/root/.no_rootfs_resize')).toBeTruthy();
    expect(w('/root/.not_logged_in_yet')).toMatchObject({ mode: 0o600, secret: true });
    expect(ops.filter((x) => x.op === 'mkdir').map((x) => x.path)).toEqual(['/boot/grub', '/var/lib/armbian-uefi', '/root/.ssh']);
    expect(ops.find((x) => x.path === '/root/.ssh')).toMatchObject({ mode: 0o700 });
    expect(w('/root/.ssh/authorized_keys')).toMatchObject({ content: 'ssh-ed25519 AAAAC3Nza key@pc\n', mode: 0o600 });
    for (const d of ['/etc/kernel/postinst.d', '/etc/kernel/postrm.d', '/etc/initramfs/post-update.d']) expect(w(`${d}/zz-armbian-uefi-grub`).mode).toBe(0o755);
    expect(ops).toContainEqual({ op: 'symlink', path: '/etc/systemd/system/multi-user.target.wants/armbian-uefi-firstboot.service', target: '/etc/systemd/system/armbian-uefi-firstboot.service' });
  });

  it('leaves Armbian its own first-start questions without an account, and the CM5-IO without TaishanPi fixes', () => {
    const ops = rootfsEdits({ ...boot, boardId: 'cm5io', facts: facts(), account: null, sshKey: '' });
    expect(ops.some((x) => x.path === '/root/.not_logged_in_yet' || x.path.startsWith('/root/.ssh'))).toBe(false);
    expect(ops.some((x) => /lckfb|LCKFB/.test(x.path))).toBe(false);
    expect(() => rootfsEdits({ ...boot, facts: facts({ kernels: [] }), account: null, sshKey: '' })).toThrow(/no kernel/);
  });

  it('turns the changes into a debugfs script that never holds the contents', () => {
    const ops = rootfsEdits({ ...boot, facts: facts(), account, sshKey: '' });
    const script = debugfsScript(ops, (i) => `/tmp/x/f${i}`);
    expect(script).not.toContain(account.password);
    expect(script).toContain('rm /etc/fstab\nwrite /tmp/x/f0 /etc/fstab\nsif /etc/fstab mode 0100644\nsif /etc/fstab uid 0\nsif /etc/fstab gid 0\n');
    expect(script).toMatch(/mkdir \/boot\/grub\nsif \/boot\/grub mode 040755\n/);
    expect(script).toContain('symlink /etc/systemd/system/lckfb-tspi-3m-screen.service /dev/null');
    expect(script).toMatch(/sif \/root\/.not_logged_in_yet mode 0100600/);
    expect(() => debugfsScript([{ op: 'write', path: '/etc/a b', content: '', mode: 0o644 }], () => '/t')).toThrow();
    expect(() => debugfsScript([{ op: 'write', path: '/etc/../x', content: '', mode: 0o644 }], () => '/t')).toThrow();
    expect(() => debugfsScript([{ op: 'write', path: '/etc/x', content: '', mode: 0o644 }], () => '/t m')).toThrow();
  });
});
