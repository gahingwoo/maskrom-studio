// The Armbian preparation against real e2fsprogs: a small Armbian-like ext4
// made with mkfs.ext4 -d (no root needed), inside a GPT image like
// Armbian's (root partition at sector 32768), raw and as .img.xz.
import { describe, expect, it } from 'vitest';
import { execFileSync, spawnSync } from 'node:child_process';
import { closeSync, mkdirSync, mkdtempSync, openSync, readFileSync, rmSync, statSync, symlinkSync, writeFileSync, writeSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { applyEdits, catFile, extractRootfs, findE2fsprogs, inspectRootfs, newUuid, statPath } from '../src/main/armbian-image';
import { ext4Superblock } from '../src/woa/armbian';
import { buildGpt } from '../src/woa/gpt';

const e2fs = findE2fsprogs();
const mkfs = ['/usr/sbin/mkfs.ext4', '/sbin/mkfs.ext4'].find((p) => { try { return statSync(p).isFile(); } catch { return false; } });
const hasXz = spawnSync('xz', ['--version']).status === 0;
const OLD = '0bb4374f-5bdf-42c2-b951-03fc3cb84ca8';
const FS_BYTES = 48 << 20;

/** An Armbian-like root file system tree, and the image around it. */
function fakeArmbian(dir: string, board = 'lckfb-taishanpi-3m'): { image: string; fs: string } {
  const t = join(dir, 'tree');
  const put = (p: string, content: string) => { mkdirSync(join(t, p, '..'), { recursive: true }); writeFileSync(join(t, p), content); };
  put('etc/armbian-release', `# PLEASE DO NOT EDIT THIS FILE\nBOARD=${board}\nBOARD_NAME="Taishan Pi 3M"\nARCH=arm64\nBOOT_SOC=rk3576\nVERSION=26.11.0-trunk\n`);
  put('etc/fstab', `UUID=${OLD} / ext4 defaults,errors=remount-ro 0 1\ntmpfs /tmp tmpfs defaults,nosuid 0 0\n`);
  put('boot/armbianEnv.txt', `verbosity=1\nrootdev=UUID=${OLD}\nrootfstype=ext4\n`);
  put('boot/vmlinuz-7.3.4-edge-rockchip64', 'kernel');
  put('boot/initrd.img-7.3.4-edge-rockchip64', 'initrd');
  put('boot/System.map-7.3.4-edge-rockchip64', 'map');
  put('root/.not_logged_in_yet', '');
  put('usr/lib/systemd/system/lckfb-tspi-3m-screen.service', '[Unit]\n');
  put('usr/share/alsa/ucm2/conf.d/simple-card/rockchip-es8388.conf', 'Syntax 6\n');
  put('etc/kernel/postinst.d/initramfs-tools', '#!/bin/sh\n');
  for (const d of ['etc/kernel/postrm.d', 'etc/initramfs/post-update.d', 'etc/systemd/system/multi-user.target.wants', 'usr/sbin', 'var/lib', 'etc/default']) mkdirSync(join(t, d), { recursive: true });
  symlinkSync('boot/vmlinuz-7.3.4-edge-rockchip64', join(t, 'vmlinuz'));
  const fs = join(dir, 'rootfs.ext4');
  execFileSync('truncate', ['-s', String(FS_BYTES), fs]);
  execFileSync(mkfs!, ['-q', '-F', '-t', 'ext4', '-b', '4096', '-O', 'metadata_csum,64bit', '-U', OLD, '-L', 'armbi_root', '-d', t, fs]);
  const sectors = 32768 + FS_BYTES / 512 + 34;
  const gpt = buildGpt({ diskSectors: sectors, diskGuid: newUuid(), keep: null, parts: [
    { type: 'b921b045-1df0-41c3-af44-4c6f280d3fae', guid: newUuid(), firstLba: 32768, lastLba: 32768 + FS_BYTES / 512 - 1, name: 'rootfs' },
  ] });
  const image = join(dir, 'Armbian_test_Lckfb-taishanpi-3m_trixie_edge_7.3.4_gnome_desktop.img');
  execFileSync('truncate', ['-s', String(sectors * 512), image]);
  const fd = openSync(image, 'r+');
  writeSync(fd, gpt.primary, 0, gpt.primary.length, 0);
  writeSync(fd, gpt.backup, 0, gpt.backup.length, gpt.backupStart * 512);
  writeSync(fd, readFileSync(fs), 0, FS_BYTES, 32768 * 512);
  closeSync(fd);
  return { image, fs };
}

describe.skipIf(!e2fs || !mkfs)('Armbian root file system, prepared with e2fsprogs', () => {
  const boot = { boardId: 'tspi3m' as const, defaultOs: 'armbian' as const, timeout: 5 };
  const account = { user: 'woo', realName: 'Woo', password: "pa'ss word", locale: 'en_US.UTF-8', timeZone: 'Asia/Hong_Kong' };

  it('copies out the root partition of a raw image and of an .img.xz, unchanged', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'armbian-x-'));
    try {
      const { image, fs } = fakeArmbian(dir);
      const out = join(dir, 'out.ext4');
      let seen = 0;
      expect(await extractRootfs(image, out, (p) => { seen = p.bytes; })).toEqual({ offset: 32768 * 512, bytes: FS_BYTES });
      expect(seen).toBe(FS_BYTES);
      expect(Buffer.compare(readFileSync(out), readFileSync(fs))).toBe(0);
      if (hasXz) {
        execFileSync('xz', ['-T2', '-k', '-1', image]);
        const out2 = join(dir, 'out2.ext4');
        expect(await extractRootfs(`${image}.xz`, out2, () => {})).toEqual({ offset: 32768 * 512, bytes: FS_BYTES });
        expect(Buffer.compare(readFileSync(out2), readFileSync(fs))).toBe(0);
      }
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }, 60000);

  it('reads the board, kernels and files, and refuses an image for another board', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'armbian-i-'));
    try {
      const { fs } = fakeArmbian(dir);
      const img = inspectRootfs(e2fs!, fs, 'tspi3m');
      expect(img.release.BOARD).toBe('lckfb-taishanpi-3m');
      expect(img.facts.uuid).toBe(OLD);
      expect(img.facts.kernels).toEqual(['7.3.4-edge-rockchip64']);
      expect(img.facts.fstab?.content).toContain(`UUID=${OLD}`);
      expect(img.facts.dirs).toContain('/etc/systemd/system/multi-user.target.wants');
      expect(img.facts.dirs).not.toContain('/boot/grub');
      expect(img.label).toBe('armbi_root');
      expect(() => inspectRootfs(e2fs!, fs, 'cm5io')).toThrow(/lckfb-taishanpi-3m/);
      const other = fakeArmbian(join(dir, 'o'), 'lckfb-taishanpi');
      expect(() => inspectRootfs(e2fs!, other.fs, 'tspi3m')).toThrow(/"lckfb-taishanpi", not "lckfb-taishanpi-3m"/);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }, 60000);

  it('gives it a new UUID, puts every file in with its mode and owner, and leaves a clean file system', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'armbian-e-'));
    try {
      const { fs } = fakeArmbian(dir);
      const before = statPath(e2fs!, fs, '/boot/armbianEnv.txt')!;
      const img = inspectRootfs(e2fs!, fs, 'tspi3m');
      const uuid = newUuid();
      const ops = applyEdits(e2fs!, img, { ...boot, uuid, account, sshKey: 'ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIK key@pc' }, join(dir, 'tmp'));
      expect(ops.length).toBeGreaterThan(15);
      const sb = Buffer.alloc(2048);
      const fd = openSync(fs, 'r');
      require('node:fs').readSync(fd, sb, 0, 2048, 0);
      closeSync(fd);
      expect(ext4Superblock(new Uint8Array(sb)).uuid).toBe(uuid);
      expect(spawnSync(e2fs!.e2fsck, ['-fn', fs]).status).toBe(0);
      expect(catFile(e2fs!, fs, '/etc/fstab')).toContain(`UUID=${uuid} / ext4`);
      expect(catFile(e2fs!, fs, '/boot/armbianEnv.txt')).toContain(`rootdev=UUID=${uuid}`);
      // armbianEnv.txt keeps its owner.
      expect(statPath(e2fs!, fs, '/boot/armbianEnv.txt')).toMatchObject({ uid: before.uid, gid: before.gid, mode: before.mode });
      expect(catFile(e2fs!, fs, '/boot/grub/armbian-uefi.cfg')).toContain(`linux /boot/vmlinuz-7.3.4-edge-rockchip64 root=UUID=${uuid} rootwait rw`);
      expect(statPath(e2fs!, fs, '/root/.not_logged_in_yet')).toMatchObject({ uid: 0, gid: 0, mode: 0o600 });
      expect(catFile(e2fs!, fs, '/root/.not_logged_in_yet')).toContain("PRESET_USER_PASSWORD='pa'\\''ss word'");
      expect(statPath(e2fs!, fs, '/root/.ssh')).toMatchObject({ type: 'directory', uid: 0, gid: 0, mode: 0o700 });
      expect(statPath(e2fs!, fs, '/root/.ssh/authorized_keys')).toMatchObject({ uid: 0, gid: 0, mode: 0o600 });
      expect(statPath(e2fs!, fs, '/usr/sbin/armbian-uefi-grub-update')).toMatchObject({ mode: 0o755 });
      expect(statPath(e2fs!, fs, '/etc/systemd/system/lckfb-tspi-3m-screen.service')?.type).toBe('symlink');
      expect(catFile(e2fs!, fs, '/usr/share/alsa/ucm2/conf.d/simple-card/LCKFB-TaishanPi3M-0.conf')).toContain('rockchip-es8388.conf');
      expect(statPath(e2fs!, fs, '/root/.no_rootfs_resize')?.type).toBe('regular');
      // The files that carried the contents are gone.
      expect(readdir(join(dir, 'tmp'))).toEqual([]);
      // A second run on the same copy (a retry) works too.
      const again = inspectRootfs(e2fs!, fs, 'tspi3m');
      expect(again.facts.uuid).toBe(uuid);
      applyEdits(e2fs!, again, { ...boot, uuid: newUuid(), account: null, sshKey: '' }, join(dir, 'tmp'));
      expect(spawnSync(e2fs!.e2fsck, ['-fn', fs]).status).toBe(0);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }, 60000);
});

function readdir(d: string): string[] {
  try { return require('node:fs').readdirSync(d); } catch { return []; }
}
