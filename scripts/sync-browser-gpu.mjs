// Copies woa-rk3576's tools/rk3576-tools/setup/rk3576-browser-gpu.ps1 (and its
// tests) into src/woa/browser-gpu/, and writes src/woa/browser-gpu-script.ts,
// the script as a string for the staged install. Run after the script
// changes in woa-rk3576:
//
//   node scripts/sync-browser-gpu.mjs [path to a woa-rk3576 checkout]
//
// Without a path it only regenerates the .ts from the .ps1 that is here.
// test/browser-gpu.test.ts fails when the two disagree.
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const here = 'src/woa/browser-gpu';
const woa = process.argv[2];
if (woa) {
  copyFileSync(join(woa, 'tools/rk3576-tools/setup/rk3576-browser-gpu.ps1'), join(here, 'rk3576-browser-gpu.ps1'));
  copyFileSync(join(woa, 'tools/rk3576-tools/tests/browser-gpu.tests.ps1'), join(here, 'browser-gpu.tests.ps1'));
}
const ps1 = readFileSync(join(here, 'rk3576-browser-gpu.ps1'), 'utf8').replace(/\r\n/g, '\n');
if (/[^\x00-\x7f]/.test(ps1)) throw new Error('rk3576-browser-gpu.ps1 must be ASCII (Windows PowerShell 5.1 reads it without a BOM)');
const version = /^\$BgVersion = (\d+)/m.exec(ps1)?.[1];
if (!version) throw new Error('no $BgVersion in rk3576-browser-gpu.ps1');
writeFileSync('src/woa/browser-gpu-script.ts', `// Generated by scripts/sync-browser-gpu.mjs from src/woa/browser-gpu/rk3576-browser-gpu.ps1
// (woa-rk3576 tools/rk3576-tools/setup). Do not edit; edit the .ps1 in woa-rk3576 and sync.
export const BROWSER_GPU_VERSION = ${version};
export const BROWSER_GPU_PS1 = ${JSON.stringify(ps1)};
`);
console.log(`src/woa/browser-gpu-script.ts: rk3576-browser-gpu.ps1 version ${version}, ${ps1.length} characters`);
